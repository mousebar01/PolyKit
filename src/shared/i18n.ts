const DICTIONARIES: Record<Language, Record<TranslationKey, string>> = {
  'en-US': EN_US,
  'zh-CN': ZH_CN,
}

export function translate(
  key: TranslationKey,
  language: Language,
  params?: Record<string, string | number>,
): string {
  let text = DICTIONARIES[language][key]
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.replaceAll(`{${name}}`, String(value))
    }
  }
  return text
}

export function useI18n(): { language: Language; t: (key: TranslationKey, params?: Record<string, string | number>) => string } {
  const language = useAppStore((state) => state.language)
  const t = useCallback(
    (key: TranslationKey, params?: Record<string, string | number>) => translate(key, language, params),
    [language],
  )
  return { language, t }
}
